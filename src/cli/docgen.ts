/**
 * Per-area command pages for docs/commands (what scripts/build-docs.mjs
 * publishes): one page per top-level command plus an index, generated from the
 * same definitions `pai help` reads. Hand-written examples are spliced in from
 * `<examplesDir>/<area>.md` when present.
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { CommandDef, GroupDef } from "./define.js";
import { mdCommand } from "./help.js";

export const GEN_HEADER = "<!-- GENERATED by `pai doc --dir` from the command definitions (src/cli). Do not edit by hand. -->";

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ").trim();

export interface Page {
  name: string;
  markdown: string;
}

export function renderAreaPage(cmd: CommandDef, allAreas: string[], examples: string): string {
  // mdCommand starts with a `## pai <name>` heading; the page title replaces it.
  const body = mdCommand([cmd.name], cmd, 2).slice(1);
  const out = [GEN_HEADER, "", `# pai ${cmd.name}`, "", ...body];
  if (cmd.aliasOf === undefined && cmd.subcommands?.length) {
    out.push("## Subcommands", "", "| Command | Description |", "|---|---|");
    for (const s of cmd.subcommands) out.push(`| \`pai ${cmd.name} ${s.name}\` | ${esc(s.summary)} |`);
    out.push("");
  }
  if (examples) out.push("## Examples", "", examples, "");
  out.push("## See also", "", allAreas.filter((a) => a !== cmd.name).map((a) => `[\`pai ${a}\`](${a}.md)`).join(" · "), "", "Run `pai help <command>` to read any of these in the terminal.", "");
  return out.join("\n").replace(/\n{3,}/g, "\n\n");
}

export function renderIndex(areas: CommandDef[]): string {
  const out = [GEN_HEADER, "", "# PAI Command Reference", "", "Generated reference for every `pai` command. Read any page in the terminal with `pai help <command>`, or browse the files here.", ""];
  out.push("## Areas", "", "| Area | Description |", "|---|---|");
  for (const a of areas) out.push(`| [\`pai ${a.name}\`](${a.name}.md) | ${esc(a.summary)} |`);
  out.push("", "## All commands", "", "| Command | Description |", "|---|---|");
  const flat: Array<[string, string]> = [];
  const walk = (c: CommandDef, prefix: string) => {
    flat.push([prefix, c.summary]);
    for (const s of c.subcommands ?? []) walk(s, `${prefix} ${s.name}`);
  };
  for (const a of areas) walk(a, `pai ${a.name}`);
  flat.sort((x, y) => x[0].localeCompare(y[0]));
  for (const [c, d] of flat) out.push(`| \`${esc(c)}\` | ${esc(d)} |`);
  out.push("");
  return out.join("\n");
}

/** Every top-level command, once, sorted by name (a shortcut that repeats a name is listed once). */
export function areasOf(groups: GroupDef[]): CommandDef[] {
  const seen = new Map<string, CommandDef>();
  for (const c of groups.flatMap((g) => g.commands)) if (!seen.has(c.name)) seen.set(c.name, c);
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

export function renderPages(groups: GroupDef[], examplesDir?: string): Page[] {
  const areas = areasOf(groups);
  const names = areas.map((a) => a.name);
  const pages = areas.map((a) => {
    const f = examplesDir ? join(examplesDir, `${a.name}.md`) : "";
    const ex = f && existsSync(f) ? readFileSync(f, "utf8").trim() : "";
    return { name: `${a.name}.md`, markdown: renderAreaPage(a, names, ex) + "\n" };
  });
  pages.push({ name: "README.md", markdown: renderIndex(areas) + "\n" });
  return pages;
}

/** Replace the generated pages in `dir` (hand-written subfolders such as _examples are kept). */
export function writePages(dir: string, pages: Page[]): void {
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(dir)) if (f.endsWith(".md")) rmSync(join(dir, f));
  for (const p of pages) writeFileSync(join(dir, p.name), p.markdown);
}
