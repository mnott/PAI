/**
 * Write a file only when its content differs, so an open Obsidian sees no
 * change on a no-op sync. The generated-at stamp line is ignored in the
 * comparison: a note whose only difference is the timestamp is left alone.
 */

import { readFileSync, writeFileSync } from "node:fs";

const STAMP = /^> Auto-generated by PAI Knowledge OS — .*$/m;

let written = 0;

/** Returns true when the file was (re)written, false when it already held `content`. */
export function writeIfChanged(path: string, content: string): boolean {
  try {
    const old = readFileSync(path, "utf-8");
    if (old === content || old.replace(STAMP, "") === content.replace(STAMP, "")) return false;
  } catch {
    // missing or unreadable: write it
  }
  writeFileSync(path, content, "utf-8");
  written++;
  return true;
}

/** Files actually written by this process since start (or the last reset). */
export function filesWrittenCount(): number {
  return written;
}

export function resetFilesWrittenCount(): void {
  written = 0;
}
